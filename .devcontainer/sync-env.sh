#!/usr/bin/env bash
# Generates .devcontainer/dev.env from src/.env with DATABASE_URL pointed at
# the compose db service. Bound on top of src/.env inside the container so
# the host's bare-metal .env (which targets a localhost Postgres) doesn't
# leak in. Idempotent — exits cleanly if dev.env already exists.
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
src_env="${repo_root}/src/.env"
dev_env="${repo_root}/.devcontainer/dev.env"
local_compose="${repo_root}/.devcontainer/docker-compose.local.yml"
db_url="postgres://arxii:arxii@db:5432/arxiidev"

# Machine-local compose overrides (gitignored). devcontainer.json lists this
# file after docker-compose.yml, so it must exist; the default is a no-op.
# Put per-machine resource limits / Postgres flags here — see
# docs/devcontainer-setup.md "Resource limits and host sizing".
if [[ ! -f "$local_compose" ]]; then
  cat > "$local_compose" <<'EOF'
# Machine-local devcontainer overrides — generated by sync-env.sh, gitignored.
# Merged on top of docker-compose.yml (see devcontainer.json). Add per-machine
# resource limits or Postgres flags here; the empty mappings below are a no-op.
# Examples in docs/devcontainer-setup.md "Resource limits and host sizing".
services:
  app: {}
  db: {}
EOF
  echo "Generated $local_compose (no-op machine-local overrides)."
fi

if [[ -f "$dev_env" ]]; then
  exit 0
fi

if [[ ! -f "$src_env" ]]; then
  cat > "$dev_env" <<EOF
DEBUG=True
SECRET_KEY=$(head -c 50 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 50)
MFA_SECRETS_KEY=$(head -c 32 /dev/urandom | base64 | tr '+/' '-_')
DATABASE_URL=${db_url}
# Set your git author identity here so post-create.sh wires it into the
# container's ~/.gitconfig and your commits attribute correctly.
GIT_USER_NAME=
GIT_USER_EMAIL=
EOF
  echo "Generated $dev_env (no src/.env found; minimal defaults written)."
  exit 0
fi

cp "$src_env" "$dev_env"

# A src/.env whose last line has no newline (a trailing comment is the usual
# culprit) would turn the first append below into a continuation of that line,
# and a commented-out DATABASE_URL fails in confusing ways. Terminate it first.
if [[ -s "$dev_env" ]] && [[ "$(tail -c1 "$dev_env")" != "" ]]; then
  printf '\n' >> "$dev_env"
fi

# settings.py reads MFA_SECRETS_KEY with no default, so a dev.env without one
# cannot run any Django command in the main checkout (worktrees copy this file,
# so they all decrypt the same dev data). A Fernet key is 32 random bytes in
# urlsafe base64; generate one when the source file has none.
if ! grep -q '^MFA_SECRETS_KEY=' "$dev_env"; then
  printf 'MFA_SECRETS_KEY=%s\n' "$(head -c 32 /dev/urandom | base64 | tr '+/' '-_')" >> "$dev_env"
fi

if grep -q '^DATABASE_URL=' "$dev_env"; then
  sed -i "s|^DATABASE_URL=.*\$|DATABASE_URL=${db_url}|" "$dev_env"
else
  echo "DATABASE_URL=${db_url}" >> "$dev_env"
fi

# Add empty GIT_USER_NAME / GIT_USER_EMAIL placeholders if not already
# present, so contributors see where to put their identity for
# post-create.sh to consume.
if ! grep -q '^GIT_USER_NAME=' "$dev_env"; then
  printf '\n# Git author identity — set these so post-create.sh wires them into the container.\n' >> "$dev_env"
  printf 'GIT_USER_NAME=\n' >> "$dev_env"
fi
if ! grep -q '^GIT_USER_EMAIL=' "$dev_env"; then
  printf 'GIT_USER_EMAIL=\n' >> "$dev_env"
fi

echo "Generated $dev_env from $src_env (DATABASE_URL → compose db service)."
