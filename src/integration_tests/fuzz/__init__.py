"""The fuzz layer (#3657): malformed, hostile and boundary input at the seams
players reach, generated by Hypothesis.

Two profiles. ``ci`` (the default) is small, has no deadline (the Postgres
tier's first query can be slow) and is derandomized, so a failure in CI
reproduces on the next run and on a laptop. ``dev`` is bigger and random, for
hunting locally: ``HYPOTHESIS_PROFILE=dev just test-parity integration_tests.fuzz``.
"""

from __future__ import annotations

import os

from hypothesis import settings

settings.register_profile("ci", max_examples=50, deadline=None, derandomize=True)
settings.register_profile("dev", max_examples=500, deadline=None)
settings.load_profile(os.environ.get("HYPOTHESIS_PROFILE", "ci"))
