"""Generations of the ``arxii`` migration chain (ADR-0276).

A *generation* is one regeneration of the chain: every file
``arx manage squashmigrations arxii`` writes carries ``replaces`` naming the
whole previous generation, so Django's loader treats a database that has the
previous generation fully recorded as already at the new one (see the
``replacements`` block of ``django/db/migrations/loader.py``) and records the new
names on the next real ``migrate`` (``MigrationExecutor.check_replacements``).

The data lives in ``src/world/migrations/_generations.py``. That module is
GENERATED by ``render_generations_module`` and read back by
``parse_generations_source``; nobody edits it by hand. It is underscore-prefixed
because Django's loader imports every non-underscore module in a migrations
package as a migration.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass, field
from pathlib import Path

APP_LABEL = "arxii"
_MODULE_NAMES = {"CURRENT", "GENERATIONS", "COMMITS", "DEFERRED"}
SRC_DIR = Path(__file__).resolve().parents[1]
GENERATIONS_PATH = SRC_DIR / "world" / "migrations" / "_generations.py"

_HEADER = '''"""GENERATED by ``arx manage squashmigrations arxii`` (ADR-0276). Do not edit.

``CURRENT`` is the generation of the migration files on disk. ``GENERATIONS[n]`` is
every migration name generation ``n`` ended with (its generated files plus the
incrementals that followed), snapshotted when generation ``n + 1`` was cut.
``COMMITS[n]`` is the last commit on ``main`` whose files were generation ``n``:
a database stranded at generation ``n`` visits that commit to migrate forward.
``DEFERRED[n]`` is generation ``n``'s cycle-breaking ``AddField`` count, the baseline
the next regeneration must not silently exceed. ``REPLACED`` is the whole previous
generation; each generated file of ``CURRENT`` replaces one ``replaced_slice`` of it.
"""
'''


@dataclass(frozen=True)
class GenerationsData:
    current: int
    generations: dict[int, list[str]] = field(default_factory=dict)
    commits: dict[int, str] = field(default_factory=dict)
    deferred: dict[int, int] = field(default_factory=dict)

    @property
    def previous_names(self) -> list[str]:
        return list(self.generations.get(self.current - 1, []))


def render_generations_module(
    current: int,
    generations: dict[int, list[str]],
    commits: dict[int, str],
    deferred: dict[int, int] | None = None,
) -> str:
    """Render ``_generations.py``. Names are one per line so diffs read as lists."""
    lines = [_HEADER.rstrip("\n"), "", f"CURRENT = {current}", ""]
    if generations:
        lines.append("GENERATIONS: dict[int, list[str]] = {")
        for gen in sorted(generations):
            lines.append(f"    {gen}: [")
            lines.extend(f'        "{name}",' for name in generations[gen])
            lines.append("    ],")
        lines.append("}")
    else:
        lines.append("GENERATIONS: dict[int, list[str]] = {}")
    lines.append("")
    if commits:
        lines.append("COMMITS: dict[int, str] = {")
        lines.extend(f'    {gen}: "{sha}",' for gen, sha in sorted(commits.items()))
        lines.append("}")
    else:
        lines.append("COMMITS: dict[int, str] = {}")
    lines.append("")
    if deferred:
        lines.append("DEFERRED: dict[int, int] = {")
        lines.extend(f"    {gen}: {count}," for gen, count in sorted(deferred.items()))
        lines.append("}")
    else:
        lines.append("DEFERRED: dict[int, int] = {}")
    lines.append("")
    lines.append(f'REPLACED = [("{APP_LABEL}", name) for name in GENERATIONS.get(CURRENT - 1, [])]')
    lines.append("")
    lines.append("")
    lines.append("def replaced_slice(index: int, total: int) -> list[tuple[str, str]]:")
    lines.append(
        '    """The slice of REPLACED that generated file ``index`` of ``total`` replaces.'
    )
    lines.append("")
    lines.append("    The slices partition REPLACED, so a fresh replay records each old name once")
    lines.append(
        "    (Django records a replacing migration's ``replaces``, not its own name) and a"
    )
    lines.append("    database at the old tip still marks every generated file applied (ADR-0276).")
    lines.append('    """')
    lines.append("    return REPLACED[index - 1 :: total]")
    lines.append("")
    return "\n".join(lines)


def parse_generations_source(source: str) -> GenerationsData:
    """Read the module back without importing it (usable before Django is set up)."""
    tree = ast.parse(source)
    values: dict[str, object] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            target, value = node.targets[0], node.value
        elif isinstance(node, ast.AnnAssign):
            target, value = node.target, node.value
        else:
            continue
        wanted = isinstance(target, ast.Name) and target.id in _MODULE_NAMES
        if wanted and value is not None:
            values[target.id] = ast.literal_eval(value)  # type: ignore[union-attr]
    generations = values["GENERATIONS"]
    commits = values["COMMITS"]
    deferred = values.get("DEFERRED", {})
    return GenerationsData(
        current=int(values["CURRENT"]),  # type: ignore[call-overload]
        generations={int(k): list(v) for k, v in generations.items()},  # type: ignore[union-attr]
        commits={int(k): str(v) for k, v in commits.items()},  # type: ignore[union-attr]
        deferred={int(k): int(v) for k, v in deferred.items()},  # type: ignore[union-attr]
    )


@dataclass(frozen=True)
class GenerationVerdict:
    """Whether stock ``migrate`` may run; ``stranded_at`` is the last fully recorded generation."""

    ok: bool
    message: str = ""
    stranded_at: int | None = None


def _recovery(data: GenerationsData, stranded_at: int) -> str:
    target = stranded_at + 1
    sha = data.commits.get(target, "<unknown: COMMITS has no entry for it>")
    return (
        f"This database last fully recorded generation {stranded_at} of the arxii migration "
        f"chain; the code is at generation {data.current}. Django cannot cross that gap "
        f"(ADR-0276). Recovery: migrate at commit {sha} (the last commit at generation "
        f"{target}) first, then here again; repeat until the gap closes. Locally that is "
        "`git checkout <commit>` + `arx manage migrate`; on production it is the Stand up "
        "infra button with its `ref` input set to that commit, then pressed again with "
        "main. Set ARX_SKIP_GENERATION_GUARD=1 only if you know better."
    )


def classify_generation_state(recorded: set[str], data: GenerationsData) -> GenerationVerdict:
    """Decide whether stock ``migrate`` may run against a database.

    ``recorded`` is the set of arxii migration names in ``django_migrations``. A fresh
    database (nothing recorded) and a database that fully recorded the previous
    generation both proceed. Anything else is stranded: Django would either apply
    nothing and exit 0 (partially recorded) or try to CREATE every table (a skipped
    generation), so the verdict names where the database stands and how to move it.
    """
    if data.current <= 1 or not recorded:
        return GenerationVerdict(ok=True)
    highest_full = 0
    for gen in sorted(data.generations):
        names = data.generations[gen]
        if names and all(name in recorded for name in names):
            highest_full = gen
    if highest_full == data.current - 1:
        return GenerationVerdict(ok=True)
    nxt = highest_full + 1
    names = data.generations.get(nxt, [])
    have = sum(1 for name in names if name in recorded)
    if have:
        detail = f"generation {nxt} is partially recorded ({have} of {len(names)} migrations)"
    else:
        detail = f"generation {nxt} was never recorded (a skipped generation)"
    return GenerationVerdict(
        ok=False, message=f"{detail}. {_recovery(data, highest_full)}", stranded_at=highest_full
    )


def load_generations(path: Path = GENERATIONS_PATH) -> GenerationsData:
    return parse_generations_source(path.read_text(encoding="utf-8"))


def write_generations(data: GenerationsData, path: Path = GENERATIONS_PATH) -> None:
    path.write_text(
        render_generations_module(data.current, data.generations, data.commits, data.deferred),
        encoding="utf-8",
    )
