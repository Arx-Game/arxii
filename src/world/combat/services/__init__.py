"""Combat encounter services, split into modules (#4318).

Import from this package exactly as before: ``from world.combat.services import X``.
Every name is re-exported here, so no caller needs to know which module holds it.

The modules are ordered by dependency, not by theme. Each module imports only
from modules before it, so the import graph has no cycles. Use ``grep`` on the
name to find its module.

Names that tests patch on this package (``perform_check``, ``emit_event``, ...)
are called as ``_svc.<name>`` from inside the modules, where ``_svc`` is this
package. That makes the patch intercept those calls at call time.
"""

