def ensure_place_names() -> int:
    """Seed the place banks. Idempotent; never moves a weight staff have edited.

    Creates a regional culture when it is missing and the realm culture too if the name
    seed has not run yet. Returns the entries created.
    """
    created = 0
    for culture_name, bank in PLACE_BANKS.items():
        culture, _ = NameCulture.objects.get_or_create(name=culture_name)
        for value, weight in bank.items():
            _, was_created = NameCultureEntry.objects.get_or_create(
                culture=culture,
                part=NamePart.PLACE,
                value=value,
                defaults={"weight": weight},
            )
            created += int(was_created)
    return created
